export type BasicLabel = keyof typeof AR;

export function useBasicLabels() {
  const { language } = useTraveliunUI();
  const dict: Record<BasicLabel, string> = language === "ar" ? AR : EN;
  return (key: BasicLabel, vars?: Record<string, string | number>) =>
    dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ""));
}
