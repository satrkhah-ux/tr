export type SlaLabel = keyof typeof AR;

const AR_UNITS: Record<SlaUnit, [string, string, string]> = {
  minute: ["دقيقة", "دقيقتان", "دقائق"],
  hour: ["ساعة", "ساعتان", "ساعات"],
  day: ["يوم", "يومان", "أيام"],
};

export function useSlaLabels() {
  const { language } = useTraveliunUI();
  const dict: Record<SlaLabel, string> = language === "ar" ? AR : EN;
  const tx = (key: SlaLabel, vars?: Record<string, string | number>) => dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ""));
  const kind = (k: SlaKind) => tx(`k_${k}`);
  // Arabic counts: 1 دقيقة · 2 دقيقتان · 3–10 دقائق · 11+ دقيقة
  const unit = (u: SlaUnit, n = 1) => (language === "ar" ? AR_UNITS[u][n === 2 ? 1 : n >= 3 && n <= 10 ? 2 : 0] : tx(`u_${u}`));
  return { tx, kind, unit, language };
}
