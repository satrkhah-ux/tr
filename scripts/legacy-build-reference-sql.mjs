w("  select nullif(");
w("    regexp_replace(");
w("      translate(");
w("        lower(btrim(coalesce(txt, ''))),");
w("        'أإآٱةىيًٌٍَُِّْٰـ',");
w("        'ااااهيي'");
w("      ),");
w("      '\\s+', ' ', 'g'");
