w("-- ========== 9. airlines ==========");
w("-- Matched on the IATA designator first: it is the carrier's identity, and the");
w("-- same airline is spelled three different ways in Arabic across the two");
w("-- systems. A row with no designator is skipped — the document draws the mark");
w("-- from it, so a carrier without one has nothing to show.");
w("with incoming (legacy_id, arabic_name, english_name, code) as (values");
/**
 * The designator, as the column's CHECK will accept it: exactly two of
 * [A-Z0-9].
 *
 * The old field was free text and collected «سيارة», «AIR LIBERTÉ», «12GO» and
 * an «AA» typed behind four stray kasras. Stripping the non-alphanumerics
 * rescues the real one; the other three are names or brands, not designators,
 * and a row without one is dropped rather than guessed at.
 */
const iata = (raw) => {
  const cleaned = String(raw ?? "").toUpperCase().replace(/[^A-Z0-9]/g, "");
  return /^[A-Z0-9]{2}$/.test(cleaned) ? cleaned : null;
};
