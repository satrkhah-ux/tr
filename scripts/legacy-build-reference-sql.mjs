/**
 * `weekend` is stored as a JSON day array, 0=Sunday … 6=Saturday (the column
 * comment in the dump spells it out). Ours is the written-out English, as the
 * 0002 seed wrote it.
 */
const DAY = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
function weekendText(raw) {
  if (!raw) return null;
  try {
    const days = JSON.parse(String(raw));
    if (!Array.isArray(days) || days.length === 0) return null;
    return days.map((d) => DAY[Number(d)]).filter(Boolean).join(", ") || null;
  } catch {
    return null;
  }
}

/**
 * The weekend for a country the old system never answered.
 *
 * Only the countries that genuinely differ are listed; everywhere else the
 * working week ends on Saturday and Sunday. This is the «املئ التفاصيل
 * تلقائياً» part, and it is deliberately limited to facts that are the same for
 * every agency — a weekend is public knowledge. Nothing priced is invented.
 */
const FRI_SAT = new Set(["SA", "EG", "JO", "KW", "QA", "OM", "DZ", "LY", "YE", "SY", "IQ", "PS", "MA"]);
const derivedWeekend = (iso2) => (iso2 && FRI_SAT.has(iso2) ? "Friday, Saturday" : "Saturday, Sunday");

