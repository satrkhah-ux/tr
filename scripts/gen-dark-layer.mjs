// Generates src/app/dark-extra.css: a dark remap for every light hard-coded colour the components use that
// globals.css's hand-written dark layer does not cover (the owner, 2026-10-29: dark mode needs work everywhere).
//   node scripts/gen-dark-layer.mjs
// Rules sit in @layer utilities under :where(.dark) so a component's own `dark:` class still wins; hover/focus
// variants are remapped too (a light hover tint on a dark card is the glare the owner saw).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const css = readFileSync("src/app/globals.css", "utf8");
const covered = new Set([...css.matchAll(/\.dark \.(?:(hover\\:|focus\\:|group-hover\\:))?(bg|border|text)-\\\[\\#([0-9a-fA-F]{6})\\\]/g)].map((m) => `${m[2]}:${m[3].toLowerCase()}`));

const used = new Map(); // "variant|kind|hex" -> count
const VARIANTS = new Set(["hover", "focus", "active", "group-hover", "disabled", "focus-within"]);
function walk(dir) {
  for (const f of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, f.name);
    if (f.isDirectory()) { if (f.name !== "node_modules" && f.name !== ".next") walk(p); continue; }
    if (!/\.tsx$/.test(f.name)) continue;
    const s = readFileSync(p, "utf8");
    for (const m of s.matchAll(/(?<![\w-])((?:[a-z0-9\-\[\]=]+:)*)(bg|border|text|divide)-\[#([0-9a-fA-F]{6})\]/g)) {
      const prefixes = m[1].split(":").filter(Boolean);
      if (prefixes.includes("dark")) continue;
      const variant = prefixes.find((x) => VARIANTS.has(x)) ?? "";
      const key = `${variant}|${m[2]}|${m[3].toLowerCase()}`;
      used.set(key, (used.get(key) ?? 0) + 1);
    }
  }
}
walk("src");

function hsl(hex) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return { h: 0, s: 0, l };
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = (max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4) * 60;
  return { h, s, l };
}
function hex({ h, s, l }) {
  const a = s * Math.min(l, 1 - l);
  const f = (n) => { const k = (n + h / 30) % 12; return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))).toString(16).padStart(2, "0"); };
  return `#${f(0)}${f(8)}${f(4)}`;
}
const family = ({ h, s }) => (s < 0.12 ? "neutral" : h >= 335 || h < 22 ? "red" : h < 65 ? "amber" : h < 175 ? "green" : h < 265 ? "blue" : "violet");

/** a light surface → its dark counterpart, by family and how light it was */
function darkBg(c) {
  const f = family(c);
  const tint = { neutral: [20, 35, 47], red: [58, 26, 36], amber: [58, 47, 20], green: [18, 53, 44], blue: [23, 38, 61], violet: [38, 28, 62] }[f];
  const toHex = (rgb) => `#${rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("")}`;
  if (f === "neutral" || (f === "green" && c.s < 0.4)) return c.l >= 0.975 ? "#14231f" : c.l >= 0.935 ? "#1b2d27" : "#22372f";
  return toHex(c.l >= 0.95 ? tint.map((v) => v * 0.85) : tint);
}
const darkBorder = (c) => ({ neutral: "#294039", green: "#294039", red: "#5a2a36", amber: "#5a4a20", blue: "#2a3b5a", violet: "#3d3560" })[family(c)];
/** a dark text colour → a light one of the same hue */
function lightText(c) {
  const f = family(c);
  if (f === "neutral") return c.l < 0.2 ? "#eaf3ef" : "#a9bdb6";
  if (f === "green" && c.s < 0.5) return c.l < 0.25 ? "#d4e7e1" : "#7fd3ba";
  return hex({ h: c.h, s: Math.min(c.s, 0.7), l: 0.72 });
}

const out = [];
const seen = new Set();
for (const [key] of [...used].sort()) {
  const [variant, kind, hx] = key.split("|");
  if (!variant && covered.has(`${kind}:${hx}`)) continue;
  const c = hsl(hx);
  let decl = null;
  if (kind === "bg" && c.l >= 0.86 && !(variant === "" && c.s > 0.9)) decl = `background-color: ${darkBg(c)}`;
  else if (kind === "border" && c.l >= 0.7) decl = `border-color: ${darkBorder(c)}`;
  else if (kind === "text" && (c.l <= 0.42 || (family(c) === "red" && c.l <= 0.55))) decl = `color: ${lightText(c)}`;
  else if (kind === "divide" && c.l >= 0.7) decl = `border-color: ${darkBorder(c)}`;
  if (!decl) continue;
  const esc = `\\[\\#${hx}\\]`;
  const cls = variant ? `${variant}\\:${kind}-${esc}` : `${kind}-${esc}`;
  const sel =
    variant === "hover" ? `.${cls}:hover` : variant === "focus" ? `.${cls}:focus` : variant === "active" ? `.${cls}:active` : variant === "disabled" ? `.${cls}:disabled` : variant === "focus-within" ? `.${cls}:focus-within`
      : variant === "group-hover" ? `.group:hover .${cls}` : kind === "divide" ? `.${cls} > *` : `.${cls}`;
  const line = variant ? `.dark ${sel} { ${decl} !important; }` : `:where(.dark) ${sel} { ${decl}; }`;
  if (!seen.has(line)) { seen.add(line); out.push(line); }
}

writeFileSync(
  "src/app/dark-extra.css",
  [
    "/* GENERATED by scripts/gen-dark-layer.mjs — do not edit by hand; re-run it after adding colours to components.",
    "   The rest of the dark layer (surfaces, borders, text) is hand-written in globals.css. */",
    "@layer utilities {",
    ...out.map((l) => `  ${l}`),
    "}",
    "",
  ].join("\n"),
);
console.log(`${out.length} rules from ${used.size} colour uses`);
