// The transport order (the owner, 2026-10-26): turn the extracted legacy JSON
// into ONE idempotent Postgres file for the TRANSPORT gaps the inventory found
// (docs/transport-inventory-2026-10-26.md):
//
//   1. country_vehicles      seats/bags per (country × vehicle) — the old `cars` (63)
//   2. tour_prices           the REAL per-vehicle prices in place of the 100-SAR
//                            placeholders; only provisional rows are overwritten
//   3. tours.city_id         the tour's city where ours is null and theirs knew it
//   4. transfers (provisional) the real price for a road the import priced at 100
//   5. guide_informations    the guide notes (72 there, 4 here), new titles only
//
// Everything resolves through public.legacy_id_map exactly like
// legacy-build-reference-sql.mjs, so re-running tops up rather than duplicates,
// and a price someone has TYPED since (provisional = false) is never touched.
//
// Usage: node scripts/legacy-build-transport-sql.mjs
//   reads  data-import/extracted/*.json  (legacy-extract-reference.mjs first)
//   writes scripts/legacy-import-transport.sql   (gitignored — review, then
//          apply with scripts/db-apply.mjs after the owner's explicit yes)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const load = (t) => JSON.parse(readFileSync(join(root, `data-import/extracted/${t}.json`), "utf8"));

const q = (v) => {
  if (v === null || v === undefined) return "null";
  const s = String(v).trim();
  if (s === "") return "null";
  return `'${s.replace(/'/g, "''")}'`;
};
const collapse = (v) => String(v ?? "").replace(/\s+/g, " ").trim();

const carsTypes = load("cars_types");
const carTypeById = new Map(carsTypes.map((t) => [t.id, t]));
const carName = (id) => {
  const t = carTypeById.get(id);
  return t ? collapse(t.arabic_name) || collapse(t.english_name) : "";
};
const currencies = new Map(load("currencies").map((c) => [c.id, c]));
const iso = (currencyId) => {
  const code = currencies.get(currencyId)?.iso_code?.trim();
  return /^[A-Z]{3}$/.test(code ?? "") ? code : null;
};

const out = [];
const w = (s = "") => out.push(s);

w("-- App Travluin — legacy TRANSPORT import (the owner's transport order, 2026-10-26).");
w("--");
w("-- GENERATED by scripts/legacy-build-transport-sql.mjs. Do not hand-edit.");
w("-- Idempotent: everything joins public.legacy_id_map, re-running tops up only.");
w("-- A price typed by a person (provisional = false) is never overwritten.");
w("");
w("begin;");
w("");
w("-- the same Arabic folding the reference import uses: alef forms, ta-marbuta,");
w("-- ya, diacritics, case and spacing — without it almost nothing matches.");
w("create or replace function pg_temp.norm(txt text)");
w("returns text language sql immutable as $$");
w("  select nullif(");
w("    regexp_replace(");
w("      translate(");
w("        lower(btrim(coalesce(txt, ''))),");
w("        'أإآٱةىيًٌٍَُِّْٰـ',");
w("        'ااااهيي'");
w("      ),");
w("      '\\s+', ' ', 'g'");
w("    ), '');");
w("$$;");
w("");

// ---------------------------------------------------- 1. country_vehicles
// The old `cars`: seats and bags per (country × vehicle). The same pair can
// appear twice with different numbers; the HIGHEST legacy id (the old system's
// last word) wins. The natural key (country_id, car_type) makes this idempotent
// without a map entity.
const cars = load("cars");
const latestPair = new Map(); // `${country}-${type}` -> row with highest id
for (const r of cars) {
  if (!r.country_id || !r.car_type_id) continue;
  const key = `${r.country_id}-${r.car_type_id}`;
  const prev = latestPair.get(key);
  if (!prev || r.id > prev.id) latestPair.set(key, r);
}
const capRows = [...latestPair.values()]
  .filter((r) => carName(r.car_type_id))
  .map((r) => `  (${r.country_id}, ${q(carName(r.car_type_id))}, ${Number(r.number_of_passengers) > 0 ? Number(r.number_of_passengers) : "null"}::int, ${Number(r.number_of_bags) > 0 ? Number(r.number_of_bags) : "null"}::int)`);
w("-- ========== 1. country_vehicles ==========");
w(`-- ${capRows.length} (country × vehicle) capacities out of ${cars.length} legacy rows (latest row per pair wins).`);
w("with incoming (country_legacy, car_type, pax, bags) as (values");
w(capRows.join(",\n"));
w("),");
w("resolved as (");
w("  select (select m.new_id from public.legacy_id_map m");
w("            where m.entity='country' and m.source='app' and m.legacy_id = i.country_legacy) as country_id,");
w("    i.car_type, i.pax, i.bags");
w("  from incoming i");
w(")");
w("insert into public.country_vehicles (country_id, car_type, pax_capacity, luggage_capacity)");
w("select country_id, car_type, pax, bags from resolved where country_id is not null");
w("on conflict (country_id, car_type) do nothing;");
w("");

// --------------------------------------- the priced legacy rows, split by type
// The same endpoint renames the 2026-10-12 cleanup applied (legacy-build-
// reference-sql.mjs CITY_RENAMED) — a text match against our rows needs them.
const CITY_RENAMED = {
  "بتايا": "باتايا",
  "شنغماي": "شيانغ ماي",
  "سنغفورا": "سنغافورة",
  "هواي ان": "هوي آن",
  "قطر": "الدوحة",
  "هوتشي": "هو تشي منه",
  "صبنجة": "سبانجا",
  "مطار عرعر الدولي": "عرعر",
};
const cityText = (name) => (name == null ? name : (CITY_RENAMED[String(name).trim()] ?? name));

const transferById = new Map(load("transfers").map((t) => [t.id, t]));
const tourPriceRows = [];   // type 4 → tour_prices
const transferPriceRows = []; // type 2/3 → transfers
for (const p of load("transfer_cars_prices")) {
  const t = transferById.get(p.transfer_id);
  if (!t) continue;
  const price = Number(p.price);
  if (!Number.isFinite(price) || price <= 0) continue;
  const car = carName(p.car_type_id);
  if (t.type === 4) {
    const base = collapse(t.arabic_description) || collapse(t.english_description) || collapse(t.point_1_arabic_name);
    tourPriceRows.push({ id: p.id, car, price, currency: iso(p.currency_id), city: t.point_1_city ?? null, base });
  } else {
    const from = cityText(collapse(t.point_1_arabic_name) || collapse(t.point_1_english_name));
    const to = cityText(collapse(t.point_2_arabic_name) || collapse(t.point_2_english_name));
    transferPriceRows.push({ id: p.id, car, price, currency: iso(p.currency_id), from, to, city: t.point_1_city ?? null });
  }
}

// ------------------------------------------------------- 2. real tour prices
// legacy_id_map entity='tour' maps each PRICE row's id to the tours row it became
// (the data-tours grouping repointed folded rows at the kept one). Only a
// provisional (placeholder) price is overwritten; a missing (tour × vehicle)
// price is added as real.
w("-- ========== 2. tour_prices: the real per-vehicle prices ==========");
w(`-- ${tourPriceRows.length} legacy tour prices.`);
w("with incoming (legacy_id, car_type, price, currency) as (values");
w(tourPriceRows.map((r) => `  (${r.id}, ${q(r.car)}, ${r.price}::numeric(12,2), ${q(r.currency)})`).join(",\n"));
w("),");
w("resolved as (");
w("  select distinct on (m.new_id, i.car_type) m.new_id as tour_id, i.car_type, i.price, i.currency");
w("  from incoming i");
w("  join public.legacy_id_map m on m.entity='tour' and m.source='app' and m.legacy_id = i.legacy_id");
w("  join public.tours t on t.id = m.new_id");
w("  where i.car_type is not null");
w("  order by m.new_id, i.car_type, i.legacy_id desc");
w(")");
w("insert into public.tour_prices (tour_id, car_type, price, currency, provisional)");
w("select tour_id, car_type, price, coalesce(currency, 'SAR'), false from resolved");
w("on conflict (tour_id, car_type) do update");
w("  set price = excluded.price, currency = excluded.currency, provisional = false");
w("  where public.tour_prices.provisional;");
w("");
// A placeholder tour (typed by staff, never in legacy_id_map) still gets the
// old system's prices when its NAME matches a legacy tour IN THE SAME COUNTRY.
//
// The first run matched by name alone, and the legacy fallback names are
// GENERIC — «الجولة الأولى» exists in every country — so Indonesian rupiah
// landed on Georgian tours (the owner, 2026-10-26: «اسعار الجولات خطأ، مكتوب
// العملة متنوعة»). Now: a generic «الجولة …» name never matches at all, and
// every other name must also agree on the country, resolved from the legacy
// row's own starting city.
const GENERIC_TOUR = /^(ال)?جول[ةه]\s+(ال)?(اول[يى]?|أول[ىي]?|ثاني[ةه]?|ثالث[ةه]?|رابع[ةه]?|خامس[ةه]?|سادس[ةه]?|سابع[ةه]?|ثامن[ةه]?|تاسع[ةه]?|عاشر[ةه]?)$/;
const legacyCityCountry = new Map(load("cities").map((c) => [c.id, c.country_id]));
const namedTour = new Map(); // `${base}-${car}` -> latest row
for (const r of tourPriceRows) {
  if (!r.base || !r.car || GENERIC_TOUR.test(r.base)) continue;
  const key = `${r.base}-${r.car}`;
  const prev = namedTour.get(key);
  if (!prev || r.id > prev.id) namedTour.set(key, r);
}
w("-- …and by NAME for tours our staff typed (never mapped): same country only,");
w("-- never a generic «الجولة …» name; only placeholder prices move.");
w("with incoming (base, car_type, price, currency, country_legacy) as (values");
w([...namedTour.values()].map((r) => `  (${q(r.base)}, ${q(r.car)}, ${r.price}::numeric(12,2), ${q(r.currency)}, ${legacyCityCountry.get(r.city) ?? "null"})`).join(",\n"));
w("),");
w("located as (");
w("  select i.*, (select m.new_id from public.legacy_id_map m");
w("     where m.entity='country' and m.source='app' and m.legacy_id = i.country_legacy) as country_id");
w("  from incoming i");
w("),");
w("matched as (");
w("  select distinct on (t.id, i.car_type) t.id as tour_id, i.car_type, i.price, i.currency");
w("  from located i join public.tours t on pg_temp.norm(t.arabic_name) = pg_temp.norm(i.base)");
w("    and t.country_id = i.country_id");
w("  order by t.id, i.car_type");
w(")");
w("insert into public.tour_prices (tour_id, car_type, price, currency, provisional)");
w("select tour_id, car_type, price, coalesce(currency, 'SAR'), false from matched");
w("on conflict (tour_id, car_type) do update");
w("  set price = excluded.price, currency = excluded.currency, provisional = false");
w("  where public.tour_prices.provisional;");
w("");
w("-- a tour whose placeholder price (100) was the row's own: show the cheapest real price as the «from» price");
w("update public.tours t set price = sub.min_price, currency = coalesce(sub.currency, t.currency)");
w("from (select tour_id, min(price) as min_price, min(currency) as currency from public.tour_prices where not provisional group by tour_id) sub");
w("where sub.tour_id = t.id and t.provisional;");
w("update public.tours set provisional = false");
w("where provisional and exists (select 1 from public.tour_prices tp where tp.tour_id = tours.id and not tp.provisional);");
w("");

// ----------------------------------------------------------- 3. tours' cities
const cityOf = new Map(tourPriceRows.filter((r) => r.city).map((r) => [r.id, r.city]));
w("-- ========== 3. tours.city_id where ours is null ==========");
w(`-- ${cityOf.size} legacy tour rows carry a starting city.`);
w("with incoming (legacy_id, city_legacy) as (values");
w([...cityOf].map(([id, c]) => `  (${id}, ${c})`).join(",\n"));
w("),");
w("resolved as (");
w("  select distinct on (tm.new_id) tm.new_id as tour_id, cm.new_id as city_id");
w("  from incoming i");
w("  join public.legacy_id_map tm on tm.entity='tour' and tm.source='app' and tm.legacy_id = i.legacy_id");
w("  join public.legacy_id_map cm on cm.entity='city' and cm.source='app' and cm.legacy_id = i.city_legacy");
w("  order by tm.new_id, i.legacy_id desc");
w(")");
w("update public.tours t set city_id = r.city_id from resolved r");
w("where t.id = r.tour_id and t.city_id is null;");
w("");

// ------------------------------------------- 4. provisional transfer prices
w("-- ========== 4. transfers: the real price where ours is a placeholder ==========");
w(`-- ${transferPriceRows.length} legacy route prices; only rows still marked provisional change.`);
w("with incoming (legacy_id, price, currency) as (values");
w(transferPriceRows.map((r) => `  (${r.id}, ${r.price}::numeric(12,2), ${q(r.currency)})`).join(",\n"));
w("),");
w("resolved as (");
w("  select distinct on (m.new_id) m.new_id as transfer_id, i.price, i.currency");
w("  from incoming i");
w("  join public.legacy_id_map m on m.entity='transfer' and m.source='app' and m.legacy_id = i.legacy_id");
w("  order by m.new_id, i.legacy_id desc");
w(")");
w("update public.transfers t set price = r.price, currency = coalesce(r.currency, t.currency), provisional = false");
w("from resolved r where t.id = r.transfer_id and t.provisional;");
w("");
// A placeholder road our staff picked (never mapped) still gets the old price
// when its two ends and vehicle match a legacy road by name.
const namedRoad = new Map(); // `${from}-${to}-${car}` -> latest
for (const r of transferPriceRows) {
  if (!r.from || !r.to || !r.car) continue;
  const key = `${r.from}-${r.to}-${r.car}`;
  const prev = namedRoad.get(key);
  if (!prev || r.id > prev.id) namedRoad.set(key, r);
}
w("-- …and by NAME for roads our staff typed (never mapped): same country only;");
w("-- only placeholder prices move.");
w("with incoming (from_city, to_city, car_type, price, currency, country_legacy) as (values");
w([...namedRoad.values()].map((r) => `  (${q(r.from)}, ${q(r.to)}, ${q(r.car)}, ${r.price}::numeric(12,2), ${q(r.currency)}, ${legacyCityCountry.get(r.city) ?? "null"})`).join(",\n"));
w("),");
w("located as (");
w("  select i.*, (select m.new_id from public.legacy_id_map m");
w("     where m.entity='country' and m.source='app' and m.legacy_id = i.country_legacy) as country_id");
w("  from incoming i");
w(")");
w("update public.transfers t set price = i.price, currency = coalesce(i.currency, t.currency), provisional = false");
w("from located i");
w("where t.provisional");
w("  and t.country_id is not distinct from i.country_id");
w("  and pg_temp.norm(t.from_city) = pg_temp.norm(i.from_city)");
w("  and pg_temp.norm(t.to_city) = pg_temp.norm(i.to_city)");
w("  and pg_temp.norm(t.car_type) = pg_temp.norm(i.car_type);");
w("");

// --------------------------------------------------- 5. guide_informations
const guideCat = new Map(load("guide_categories").map((c) => [c.id, collapse(c.arabic_name)]));
const guides = load("guide_informations")
  .filter((g) => collapse(g.arabic_header) || collapse(g.arabic_text))
  .map((g) => ({
    title: collapse(g.arabic_header) || collapse(g.english_header) || collapse(g.arabic_text).slice(0, 80),
    body: collapse(g.arabic_text) ? String(g.arabic_text).trim() : null,
    category: guideCat.get(g.category_id) ?? null,
  }));
w("-- ========== 5. guide_informations ==========");
w(`-- ${guides.length} guide notes; a title we already hold is left as it is.`);
w("with incoming (category, title, body) as (values");
w(guides.map((g) => `  (${q(g.category)}, ${q(g.title)}, ${q(g.body)})`).join(",\n"));
w(")");
w("insert into public.guide_informations (category, title, body)");
w("select category, title, body from incoming i");
w("where i.title is not null and not exists (");
w("  select 1 from public.guide_informations g where btrim(g.title) = btrim(i.title));");
w("");

w("commit;");
w("");

const file = join(root, "scripts/legacy-import-transport.sql");
writeFileSync(file, out.join("\n"), "utf8");
console.log(`country_vehicles ${capRows.length} | tour_prices ${tourPriceRows.length} | transfer prices ${transferPriceRows.length} | guides ${guides.length}`);
console.log(`→ ${file}`);
