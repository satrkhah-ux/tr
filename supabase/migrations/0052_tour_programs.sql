-- The old system's day programmes, ready to drop into a new one.
--
-- app.traveliun.com kept every city's tours as `transfers` rows of type 4: a
-- name («الجولة الأولى», «جولة بحرية»), an order inside the city, and the
-- paragraph the agents had written and polished over years. The 0011 import
-- took them for PRICING only — one row per vehicle, the vehicle in the name, no
-- city and no order — so none of that text could be reused as a day.
--
-- One row per tour here, with its city and order, no price (the price stays in
-- `tours`). Filled by scripts/legacy-import-tour-programs.sql (generated by
-- scripts/legacy-build-reference-sql.mjs); edited by the admin afterwards.

create table if not exists public.tour_programs (
  id uuid primary key default gen_random_uuid(),
  country_id uuid references public.countries (id) on delete cascade,
  city_id uuid references public.cities (id) on delete set null,
  sort_order integer,
  title text not null,
  description_ar text not null default '',
  description_en text,
  /** a free day is a template too, but «fill the days» must never pick one as a tour. */
  is_free_day boolean not null default false,
  status text not null default 'Active',
  created_at timestamptz not null default now()
);

create index if not exists tour_programs_city_idx on public.tour_programs (city_id, sort_order);

alter table public.tour_programs enable row level security;

-- Text only, no money: staff edit it, and a partner building a programme in the
-- generator reads it like the other reference tables (0036).
drop policy if exists tour_programs_staff_all on public.tour_programs;
create policy tour_programs_staff_all
  on public.tour_programs for all to authenticated
  using (public.is_staff()) with check (public.is_staff());

drop policy if exists tour_programs_partner_read on public.tour_programs;
create policy tour_programs_partner_read
  on public.tour_programs for select to authenticated
  using (public.current_partner_id() is not null);

notify pgrst, 'reload schema';
